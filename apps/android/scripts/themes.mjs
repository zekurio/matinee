#!/usr/bin/env node
/*
 * The web's bundled themes as Kotlin, so the app paints with the same
 * palettes. Reads packages/ui/src/lib/theme-presets-{light,dark}.ts and the
 * families in theme-presets.ts, turns every color into #rrggbb (the light
 * Matinee theme and the status colors are written in oklch), and
 * writes app/src/main/java/.../ui/theme/ThemePresets.kt. Run it again with
 * Node 24, which reads TypeScript, after the presets change:
 *
 *     node scripts/themes.mjs
 */

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const lib = join(root, "../../packages/ui/src/lib")
const out = join(
  root,
  "app/src/main/java/io/github/zekurio/matinee/ui/theme/ThemePresets.kt",
)

const { DARK_THEME_VARIANTS } = await import(join(lib, "theme-presets-dark.ts"))
const { LIGHT_THEME_VARIANTS } = await import(join(lib, "theme-presets-light.ts"))
// Read as text: the contract's modules import each other without extensions.
const contract = readFileSync(join(root, "../../packages/contracts/src/theme.ts"), "utf8")
const THEME_COLOR_ROLES = [
  ...(/THEME_COLOR_ROLES = \[([^\]]*)\]/.exec(contract)?.[1] ?? "").matchAll(/"(\w+)"/g),
].map(([, role]) => role)
if (THEME_COLOR_ROLES.length === 0) throw new Error("No color roles in the contract")

const variants = new Map(
  [...LIGHT_THEME_VARIANTS, ...DARK_THEME_VARIANTS].map((v) => [v.id, v]),
)

// builtinTheme("catppuccin", "Catppuccin", ["catppuccin-latte", …])
const source = readFileSync(join(lib, "theme-presets.ts"), "utf8")
const families = [
  ...source.matchAll(/builtinTheme\(\s*(\w+|"[^"]+"),\s*"([^"]+)",\s*\[([^\]]*)\]/g),
].map(([, id, label, ids]) => ({
  id: id === "MATINEE_THEME_ID" ? "matinee" : JSON.parse(id),
  label,
  variants: [...ids.matchAll(/"([^"]+)"/g)].map(([, variant]) => variant),
}))

/** sRGB bytes from `#rrggbb` or `oklch(l c h)`, the forms the presets use. */
function parseColor(value) {
  const hexMatch = /^#([0-9a-f]{6})$/i.exec(value.trim())
  if (hexMatch) {
    const n = Number.parseInt(hexMatch[1], 16)
    return { r: n >> 16, g: (n >> 8) & 255, b: n & 255 }
  }
  const lch = /^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*\)$/i.exec(value.trim())
  if (!lch) return null
  const [l, c, h] = lch.slice(1).map(Number)
  const a = c * Math.cos((h * Math.PI) / 180)
  const b = c * Math.sin((h * Math.PI) / 180)
  // OKLab to linear sRGB, as theme-color-math.ts does it, clipped to sRGB.
  const L = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const M = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const S = (l - 0.0894841775 * a - 1.291485548 * b) ** 3
  const encode = (x) => {
    const v = x <= 0.0031308 ? x * 12.92 : 1.055 * x ** (1 / 2.4) - 0.055
    return Math.round(Math.min(1, Math.max(0, v)) * 255)
  }
  return {
    r: encode(4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S),
    g: encode(-1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S),
    b: encode(-0.0041960863 * L - 0.7034186147 * M + 1.707614701 * S),
  }
}

function hex(value, where) {
  const color = parseColor(value)
  if (!color) throw new Error(`Can't read ${value} in ${where}`)
  const channel = (n) => Math.round(n).toString(16).padStart(2, "0").toUpperCase()
  return `0xFF${channel(color.r)}${channel(color.g)}${channel(color.b)}`
}

const kotlin = (text) => JSON.stringify(text).replaceAll("$", "\\$")

function variantCode(id) {
  const variant = variants.get(id)
  if (!variant) throw new Error(`Unknown theme preset: ${id}`)
  const colors = THEME_COLOR_ROLES.map(
    (role) => `${role} = Color(${hex(variant.colors[role], `${id}.${role}`)})`,
  )
  return [
    `        ThemeVariant(`,
    `            id = ${kotlin(variant.id)},`,
    `            label = ${kotlin(variant.label)},`,
    `            appearance = Appearance.${variant.appearance === "light" ? "Light" : "Dark"},`,
    `            colors = ThemeColors(`,
    ...colors.map((line) => `                ${line},`),
    `            ),`,
    `        ),`,
  ].join("\n")
}

const body = families
  .map((family) =>
    [
      `    ThemeFamily(`,
      `        id = ${kotlin(family.id)},`,
      `        label = ${kotlin(family.label)},`,
      `        custom = false,`,
      `        variants = listOf(`,
      ...family.variants.map((id) =>
        variantCode(id)
          .split("\n")
          .map((line) => `    ${line}`)
          .join("\n"),
      ),
      `        ),`,
      `    ),`,
    ].join("\n"),
  )
  .join("\n")

writeFileSync(
  out,
  `// Generated by scripts/themes.mjs from packages/ui/src/lib/theme-presets*.ts. Don't edit.
package io.github.zekurio.matinee.ui.theme

import androidx.compose.ui.graphics.Color

/** The web's bundled themes, Matinee first. */
val BUILTIN_THEMES: List<ThemeFamily> = listOf(
${body}
)
`,
)
console.log(`${families.length} themes, ${families.reduce((n, f) => n + f.variants.length, 0)} variants`)
