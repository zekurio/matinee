import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

import { build } from "esbuild"
import { format } from "oxfmt"

const output = new URL("../src/plugins/sandbox/prelude.gen.ts", import.meta.url)
const result = await build({
  entryPoints: [
    fileURLToPath(
      new URL("../src/plugins/sandbox/prelude/index.ts", import.meta.url),
    ),
  ],
  bundle: true,
  write: false,
  format: "iife",
  platform: "neutral",
  target: "es2022",
  minify: true,
  legalComments: "none",
  charset: "ascii",
})
const outputFile = result.outputFiles[0]
if (!outputFile) throw new Error("esbuild did not emit the prelude")
const code = outputFile.text.trim()
const generated = `// Generated by pnpm --filter @matinee/server exec tsx scripts/plugin-prelude.ts.\n// Do not edit. The source is sandbox/prelude/index.ts.\nexport const PRELUDE =\n  ${JSON.stringify(code)}\n`
const formatted = await format(fileURLToPath(output), generated, {
  semi: false,
})
if (formatted.errors.length)
  throw new Error("Could not format generated prelude")
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8").catch(() => "")) !== formatted.code) {
    process.stderr.write(
      "prelude.gen.ts is stale. Run scripts/plugin-prelude.ts.\n",
    )
    process.exitCode = 1
  }
} else await writeFile(output, formatted.code)
