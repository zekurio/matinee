/** JSON Schema for the contract's `t` schemas, for coercion and the document. */
const schemaConverters = [new TypeBoxToJsonSchemaConverter()]

/**
 * The REST face of the router. Query strings and multipart fields arrive as
 * text, so the coercion plugin turns them into the numbers, booleans, and
 * dates the contract asks for before validation.
 */
export const openapi = new OpenAPIHandler(router, {
  plugins: [new SmartCoercionPlugin({ schemaConverters })],
  interceptors: [onError(logError)],
})

