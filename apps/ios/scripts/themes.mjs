#!/usr/bin/env node
/*
 * Matinee's palettes as Swift, so the app paints with the web's colors, as
 * apps/android/scripts/themes.mjs does for Kotlin. Reads
 * packages/ui/src/lib/theme-presets.ts, turns every color into sRGB bytes
 * (the light palette and the status colors are written in oklch), and
 * writes the presets, public, for the kit in Packages/MatineeKit, which
 * owns the app's theme, and the launch screen's background color, which is
 * the palette's background. Run it again with
 * Node 24, which reads TypeScript, after the presets change:
 *
 *     node scripts/themes.mjs           # write them
 *     node scripts/themes.mjs --check   # fail when they're out of date
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const repo = join(root, "../..")
const lib = join(repo, "packages/ui/src/lib")
const launchOut = join(
  root,
  "Matinee/Resources/Assets.xcassets/LaunchBackground.colorset/Contents.json",
)
const kitPresetsOut = join(
  root,
  "Packages/MatineeKit/Sources/MatineeKit/Theme/ThemePresets.gen.swift",
)

const { MATINEE_THEME } = await import(join(lib, "theme-presets.ts"))
// Read as text: the contract's modules import each other without extensions.
const contract = readFileSync(
  join(repo, "packages/contracts/src/theme.ts"),
  "utf8",
)
const THEME_COLOR_ROLES = [
  ...(/THEME_COLOR_ROLES = \[([^\]]*)\]/.exec(contract)?.[1] ?? "").matchAll(
    /"(\w+)"/g,
  ),
].map(([, role]) => role)
if (THEME_COLOR_ROLES.length === 0)
  throw new Error("No color roles in the contract")

/** sRGB bytes from `#rrggbb` or `oklch(l c h)`, the forms the presets use. */
function parseColor(value) {
  const hexMatch = /^#([0-9a-f]{6})$/i.exec(value.trim())
  if (hexMatch) {
    const n = Number.parseInt(hexMatch[1], 16)
    return { r: n >> 16, g: (n >> 8) & 255, b: n & 255 }
  }
  const lch = /^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*\)$/i.exec(
    value.trim(),
  )
  if (!lch) return null
  const [l, c, h] = lch.slice(1).map(Number)
  const a = c * Math.cos((h * Math.PI) / 180)
  const b = c * Math.sin((h * Math.PI) / 180)
  // OKLab to linear sRGB, as theme-color-math.ts does it, clipped to sRGB.
  const L = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const M = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const S = (l - 0.0894841775 * a - 1.291485548 * b) ** 3
  const encode = (x) => {
    const v = x <= 0.0031308 ? x * 12.92 : 1.055 * x ** (1 / 2.4) - 0.055
    return Math.round(Math.min(1, Math.max(0, v)) * 255)
  }
  return {
    r: encode(4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S),
    g: encode(-1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S),
    b: encode(-0.0041960863 * L - 0.7034186147 * M + 1.707614701 * S),
  }
}

function color(value, where) {
  const parsed = parseColor(value)
  if (!parsed) throw new Error(`Can't read ${value} in ${where}`)
  return parsed
}

const byte = (n) => Math.round(n).toString(16).padStart(2, "0").toUpperCase()

function colorsCode(appearance) {
  const colors = MATINEE_THEME[appearance]
  return [
    `ThemeColors(`,
    THEME_COLOR_ROLES.map((role) => {
      const { r, g, b } = color(colors[role], `${appearance}.${role}`)
      return `  ${role}: RGB(0x${byte(r)}${byte(g)}${byte(b)})`
    }).join(",\n"),
    `)`,
  ].join("\n")
}

const kitPresets = `// Generated by apps/ios/scripts/themes.mjs from packages/ui/src/lib/theme-presets.ts. Don't edit.

/// Matinee's light palette, as the web has it.
public nonisolated let MATINEE_LIGHT = ${colorsCode("light")}

/// Matinee's dark palette, as the web has it.
public nonisolated let MATINEE_DARK = ${colorsCode("dark")}
`

function launchColor(appearance) {
  const { r, g, b } = color(
    MATINEE_THEME[appearance].background,
    `${appearance}.background`,
  )
  const entry = {
    color: {
      "color-space": "srgb",
      components: {
        alpha: "1.000",
        blue: `0x${byte(b)}`,
        green: `0x${byte(g)}`,
        red: `0x${byte(r)}`,
      },
    },
    idiom: "universal",
  }
  return appearance === "dark"
    ? { appearances: [{ appearance: "luminosity", value: "dark" }], ...entry }
    : entry
}

const launch = `${JSON.stringify(
  {
    colors: [launchColor("light"), launchColor("dark")],
    info: { author: "xcode", version: 1 },
  },
  null,
  2,
)}\n`

const outputs = new Map([
  [launchOut, launch],
  [kitPresetsOut, kitPresets],
])
const check = process.argv.includes("--check")
const stale = [...outputs].filter(
  ([path, text]) => !existsSync(path) || readFileSync(path, "utf8") !== text,
)
if (check) {
  if (stale.length > 0) {
    const names = stale.map(([path]) => relative(root, path)).join(", ")
    process.stderr.write(`${names} out of date; run scripts/themes.mjs\n`)
    process.exit(1)
  }
} else {
  for (const [path, text] of stale) {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, text)
    process.stdout.write(`${relative(root, path)}\n`)
  }
}
