"""Generate Flutter's server message table using the Android importer's catalog order and argument positions."""

import json
import re
import sys
from pathlib import Path

FLUTTER = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FLUTTER.parent / "android/scripts"))
import web_strings as web


def literal(value):
    quoted = json.dumps(value, ensure_ascii=False).replace("$", r"\$")
    if "'" in value:
        return quoted
    return "'" + quoted[1:-1].replace(r'\"', '"') + "'"


def entries():
    for area in web.MATCHED_AREAS:
        catalogs = {
            lang: web.messages(web.LOCALES / lang / f"{area}.ts")
            for lang in web.LANGUAGES
        }
        for key, base in catalogs["en"].items():
            text = web.english_form(base)
            names = web.PLACEHOLDER.findall(text)
            plural = isinstance(base, dict)
            positions = web.order(base, [catalogs["de"].get(key)])
            getter = re.sub(r"_(\w)", lambda m: m[1].upper(), web.name(key))
            args = []
            for name in positions:
                if plural and name == "count":
                    args.append("count")
                elif name in names:
                    args.append(f"values[{literal(name)}]!")
                else:
                    raise ValueError(f"{key}: no capture for {name}")
            if plural and "count" not in positions:
                args.insert(0, "count")
            if args:
                getter += f"({', '.join(args)})"
            captures = ", ".join(literal(name) for name in names)
            yield (
                f"  ServerMessage({literal(text)}, [{captures}], "
                f"(l, values, count) => l.{getter}"
                + (", plural: true" if plural else "") + "),"
            )


source = """// Generated by scripts/server_messages.py. Don't edit.
// Run pnpm server-messages:dart after changing the web catalog.
import 'app_localizations.dart';

class ServerMessage {
  const ServerMessage(this.text, this.names, this.localize, {this.plural = false});

  final String text;
  final List<String> names;
  final String Function(AppLocalizations, Map<String, String>, int) localize;
  final bool plural;
}

final serverMessages = <ServerMessage>[
""" + "\n".join(entries()) + "\n];\n"

output = FLUTTER / "lib/l10n/server_messages.g.dart"
if "--check" in sys.argv:
    if not output.exists() or output.read_text() != source:
        sys.exit("server_messages.g.dart is out of date. Run pnpm server-messages:dart")
else:
    output.write_text(source)
