// The package exports each icon, aliases included, by its PascalCase name.
const icons = await import(pathToFileURL(lucide).href)

function iconNodes(name) {
  const exported = name.replace(/(?:^|-)([a-z0-9])/g, (_, c) => c.toUpperCase())
  const nodes = icons[exported]
  if (!nodes) throw new Error(`lucide has no icon ${name}`)
  return nodes
}

async function entry([field, resource]) {
  const [name, variant] = resource.split(":")
  const filled = variant === "filled"
  const nodes = iconNodes(name)
  const elements = nodes.map(([tag, attributes]) => {
    const attrs = Object.entries(attributes)
      .filter(([key]) => key !== "key")
      .map(([key, value]) => `${key}="${value}"`)
      .join(" ")
    return `    <${tag} ${attrs}/>`
  })
  const fill = filled ? "#fff" : "none"
  return [
    `  static const ${field} = '''`,
    `  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="${fill}"`,
    '    stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">',
    ...elements,
    "  </svg>''';",
  ].join("\n")
}

const entries = await Promise.all(Object.entries(resources).map(entry))
const source = `// Generated by scripts/lucide.mjs from lucide (ISC license).

abstract final class Lucide {
${entries.join("\n\n")}
}
`

if (process.argv.includes("--check")) {
  const current = await readFile(out, "utf8").catch(() => null)
  if (current !== source) {
    process.stderr.write(
      "lib/kit/lucide.g.dart is out of date. Run: pnpm icons:dart\n",
    )
    process.exit(1)
  }
} else {
  await writeFile(out, source)
}
