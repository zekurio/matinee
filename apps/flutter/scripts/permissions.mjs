#!/usr/bin/env node
// Copy the permission names into lib/core/permissions.g.dart from
// packages/contracts/src/permissions.ts: every permission, in the
// contract's order, and the ones every account holds. The OpenAPI
// document types a permission list as strings, so the API client has
// neither. With --check, fail instead of writing when the file is stale.

import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const contract = join(root, "../../packages/contracts/src/permissions.ts")
const out = join(root, "lib/core/permissions.g.dart")

const source = readFileSync(contract, "utf8")

// The string literals of the array that `header` opens, comments aside.
// Anything else in it fails, so a change of form can't drop names.
function names(header) {
  const start = header.exec(source)
  if (!start) throw new Error(`permissions.ts: no ${header}`)
  const end = source.indexOf("]", start.index + start[0].length)
  const body = source
    .slice(start.index + start[0].length, end)
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/[^\n]*/g, "")
  const list = []
  for (const item of body.split(",")) {
    const text = item.trim()
    if (text === "") continue
    const match = /^"([A-Za-z]+(?:\.[A-Za-z]+)?)"$/.exec(text)
    if (!match) throw new Error(`permissions.ts: can't read ${text}`)
    list.push(match[1])
  }
  if (list.length === 0) throw new Error(`permissions.ts: ${header} is empty`)
  return list
}

const all = names(/export const PERMISSIONS = \[/)
const base = names(/export const BASE_PERMISSIONS: readonly Permission\[\] = \[/)
for (const name of base) {
  if (!all.includes(name)) throw new Error(`${name} isn't in PERMISSIONS`)
}
if (new Set(all).size !== all.length) throw new Error("PERMISSIONS repeats")

const constant = (name) =>
  name.replace(/\.([a-z])/g, (_, letter) => letter.toUpperCase())

const dart = `// Generated by scripts/permissions.mjs from
// packages/contracts/src/permissions.ts. Run: pnpm permissions:dart

/// What an account or an API token may do, as the contract names it.
abstract final class Permission {
${all.map((name) => `  static const ${constant(name)} = '${name}';`).join("\n")}

  /// Every permission, in the contract's order.
  static const values = <String>[
${all.map((name) => `    ${constant(name)},`).join("\n")}
  ];

  /// What every account holds, whatever its groups say.
  static const base = <String>[
${base.map((name) => `    ${constant(name)},`).join("\n")}
  ];
}
`

if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== dart) {
    process.stderr.write(
      "lib/core/permissions.g.dart is out of date. Run: pnpm permissions:dart\n",
    )
    process.exit(1)
  }
} else {
  writeFileSync(out, dart)
}
