#!/usr/bin/env node
// Copy the logo into the kit from brand/logo-light.svg and logo-dark.svg,
// which brand/wordmark.py writes. With --check, fail instead of writing
// when lib/kit/logo.g.dart is stale.
//
// The brand files pad the logo by 8% of the word's height on every side.
// The kit's copy drops the padding at the top and the sides, so the logo
// starts where it's placed, and keeps it at the bottom, where the round
// letters dip below the baseline.

import { readFile, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const brand = join(root, "../../brand")
const out = join(root, "lib/kit/logo.g.dart")

const number = (value) => String(Number(value.toFixed(2)))

async function logo(name) {
  const svg = await readFile(join(brand, name), "utf8")
  const box = svg.match(/viewBox="([^"]+)"/)
  if (!box) throw new Error(`${name} has no viewBox`)
  const [x, y, width, height] = box[1].split(/\s+/).map(Number)
  // wordmark.py: viewBox (-pad, -pad, w + 2 pad, h + 2 pad), pad = 0.08 h.
  const pad = -x
  if (pad <= 0 || y !== x) throw new Error(`${name} isn't padded as expected`)
  const word = height - 2 * pad
  const cropped = svg
    .replace(/<!--[\s\S]*?-->\s*/g, "")
    .replace(
      box[0],
      `viewBox="0 0 ${number(width - 2 * pad)} ${number(word + pad)}"`,
    )
    .trim()
  return { svg: cropped, width: width - 2 * pad, word, depth: pad }
}

const light = await logo("logo-light.svg")
const dark = await logo("logo-dark.svg")
if (light.width !== dark.width || light.word !== dark.word) {
  throw new Error("logo-light.svg and logo-dark.svg differ in size")
}

const source = `// Generated by scripts/logo.mjs from brand/logo-light.svg and
// brand/logo-dark.svg. Run: pnpm logo:dart

abstract final class LogoArt {
  /// The logo's width, and the room below the baseline, as fractions of
  /// the word's height.
  static const aspect = ${light.width / light.word};
  static const depth = ${light.depth / light.word};

  static const light = '''
${light.svg}''';

  static const dark = '''
${dark.svg}''';
}
`

if (process.argv.includes("--check")) {
  const current = await readFile(out, "utf8").catch(() => null)
  if (current !== source) {
    process.stderr.write(
      "lib/kit/logo.g.dart is out of date. Run: pnpm logo:dart\n",
    )
    process.exit(1)
  }
} else {
  await writeFile(out, source)
}
