/// The overrides Explore needs with [exploreRails] and [exploreRows]: a
/// signed-in account and no network.
List<Override> exploreOverrides() => [
  authStateProvider.overrideWithValue(
    SignedIn(
      'https://media.example.com',
      User.fromJson(const {
        'id': 'id-ben',
        'username': 'ben',
        'displayName': null,
        'role': 'user',
        'permissions': <String>[],
        'avatarUrl': null,
        'avatarSource': 'none',
        'playback': null,
        'library': {'showSpecials': true},
        'sharing': {'favorites': false, 'stats': false},
      }),
    ),
  ),
  apiProvider.overrideWithValue(null),
  discoverRailsProvider.overrideWith((ref) async => exploreRails()),
  discoverRowProvider.overrideWith(
    (ref, key) async => exploreRows()[railKey(key.rail)]!,
  ),
];

/// The Explore tab over the stubs.
Widget exploreApp() => ProviderScope(
  overrides: exploreOverrides(),
  child: MaterialApp(
    locale: const Locale('en'),
    localizationsDelegates: AppLocalizations.localizationsDelegates,
    supportedLocales: AppLocalizations.supportedLocales,
    theme: MatineeTheme.data(matineeDark),
    // The shell gives the tab its Material text style and surface.
    home: const Material(child: ExploreScreen()),
  ),
);
